--[[
    Guns of Tien -- cartons and crates of Ammo Maker's part boxes (user, 2026-11-21, with the permission of Ammo
    Maker's author, who plans the same in Ammo Maker itself; sandbox option GunsOfTien.AmmoPartCartons switches
    ours off for that day).

    Ammo Maker packs 25 parts into a box or a bag (its PackAmmoParts / UnpackAmmoParts, generated at
    OnInitGlobalModData from ammoMakerAmmoParts' boxType / bagType) and stops there. Here 15 boxes or bags of one kind
    make a carton and 5 cartons a crate, both ways, in hand like ammunition cartons. Player-made only: nothing
    places them in loot. The items (scripts/GunsOfTien/items_ammomaker_cartons.txt) and the pairs
    (AmmoPartCartonsTable.lua) are generated by scripts/gen_scripts.py ammomaker_part_cartons(): every part box and
    bag of Ammo Maker 42.20 plus this mod's three.

    The four recipes (scripts/GunsOfTien/recipes_ammomaker_cartons.txt) are empty placeholders: their inputs and
    mappers name Ammo Maker's items, and an itemMapper naming a missing item throws in
    OutputMapper.OnPostWorldDictionaryInit, which stops that pass for every recipe after it. So they are filled with
    `recipe:Load` at OnInitGlobalModData (before PostWorldDictionaryInit resolves them), only with Ammo Maker and
    only with the boxes whose item scripts exist (an Ammo Maker update could drop one). Without Ammo Maker all four
    are hidden (GunsOfTien_HideAmmoMakerRecipe, AmmoMaker.lua). With the option off only the two packing recipes
    are hidden: cartons and crates already made can still be opened. The option is read once per world load
    (a change takes effect the next time the game is loaded); scripts are reloaded on leaving a game, so a
    placeholder is empty again at the next load, and the empty-inputs check only guards a second OnInitGlobalModData
    in one script session.
--]]

local AMMO_MAKER = type(ammoMakerAmmoData) == "table" and type(ammoMakerAmmoParts) == "table"

local PACK_CARTON = "GunsOfTien_PlaceAmmoPartBoxesInCarton"
local OPEN_CARTON = "GunsOfTien_OpenCartonOfAmmoPartBoxes"
local PACK_CRATE = "GunsOfTien_PlaceAmmoPartBoxesInCrate"
local OPEN_CRATE = "GunsOfTien_OpenCrateOfAmmoPartBoxes"

local function isEnabled()
    local vars = SandboxVars and SandboxVars.GunsOfTien
    return vars ~= nil and vars.AmmoPartCartons == true
end

-- `item <count> [<inputs>] mappers[partType] flags[...]` -> `item <out> mapper:partType`
local RECIPE = [[
{
    inputs
    {
        item %d [%s] mappers[partType] flags[%s],
    }
    outputs
    {
        item %d mapper:partType,
    }
    itemMapper partType
    {
%s
    }
}
]]

local PACK_FLAGS = "AllowFavorite;InheritFavorite;IsExclusive"
local OPEN_FLAGS = "AllowFavorite;InheritFavorite"

--- Fill one placeholder from (input, output) pairs.
local function fill(name, pairs_, inCount, outCount, flags)
    local recipe = ScriptManager.instance:getCraftRecipe(name)
    if not recipe or recipe:getInputs():size() > 0 or #pairs_ == 0 then return end
    local inputs, mapper = {}, {}
    for i, pair in ipairs(pairs_) do
        inputs[i] = pair[1]
        mapper[i] = "        " .. pair[2] .. " = " .. pair[1] .. ","
    end
    recipe:Load(name, string.format(RECIPE, inCount, table.concat(inputs, ";"), flags, outCount,
        table.concat(mapper, "\n")))
end

local function onInitGlobalModData()
    local names = { PACK_CARTON, OPEN_CARTON, PACK_CRATE, OPEN_CRATE }
    local data = GunsOfTien_AmmoPartCartons
    if not AMMO_MAKER or type(data) ~= "table" then
        for _, name in ipairs(names) do GunsOfTien_HideAmmoMakerRecipe(name) end
        return
    end
    local scripts = ScriptManager.instance
    local boxToCarton, cartonToBox, cartonToCrate, crateToCarton = {}, {}, {}, {}
    for _, row in ipairs(data) do
        local box, carton, crate = row[1], row[2], row[3]
        if scripts:getItem(box) and scripts:getItem(carton) and scripts:getItem(crate) then
            boxToCarton[#boxToCarton + 1] = { box, carton }
            cartonToBox[#cartonToBox + 1] = { carton, box }
            cartonToCrate[#cartonToCrate + 1] = { carton, crate }
            crateToCarton[#crateToCarton + 1] = { crate, carton }
        end
    end
    local perCarton, perCrate = data.boxesPerCarton, data.cartonsPerCrate
    fill(OPEN_CARTON, cartonToBox, 1, perCarton, OPEN_FLAGS)
    fill(OPEN_CRATE, crateToCarton, 1, perCrate, OPEN_FLAGS)
    if isEnabled() then
        fill(PACK_CARTON, boxToCarton, perCarton, 1, PACK_FLAGS)
        fill(PACK_CRATE, cartonToCrate, perCrate, 1, PACK_FLAGS)
    else
        GunsOfTien_HideAmmoMakerRecipe(PACK_CARTON)
        GunsOfTien_HideAmmoMakerRecipe(PACK_CRATE)
    end
end

Events.OnInitGlobalModData.Add(onInitGlobalModData)
